function successType(operation) {
  const success = Object.entries(operation.responses || {}).find(([statusCode]) => /^2\d\d$/.test(statusCode))
  if (!success) return 'unknown'
  const [statusCode, unresolvedResponse] = success
  if (statusCode === '204') return 'void'
  const response = resolveNode(unresolvedResponse)
  const responseSchema = response?.content?.['application/json']?.schema
  if (!responseSchema) return 'unknown'
  const resolvedSchema = resolveNode(responseSchema)
  const dataSchema = resolvedSchema?.properties?.data
  return schemaToTs(dataSchema || responseSchema)
}

