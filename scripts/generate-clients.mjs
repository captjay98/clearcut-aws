function temporarySiblingPath(destination, kind) {
  return path.join(
    path.dirname(destination),
    `.${path.basename(destination)}.${process.pid}.${randomUUID()}.${kind}`,
  )
}

function publishGeneratedOutputs(outputs) {
  const staged = []
  const backups = []
  const promoted = new Set()

  try {
    for (const output of outputs) {
      fs.mkdirSync(path.dirname(output.destination), { recursive: true })
      const temporaryPath = temporarySiblingPath(output.destination, 'tmp')
      fs.writeFileSync(temporaryPath, output.content, { encoding: 'utf-8', flag: 'wx' })
      staged.push({ ...output, temporaryPath })
    }

    for (const output of outputs) {
      if (!fs.existsSync(output.destination)) continue
      const backupPath = temporarySiblingPath(output.destination, 'backup')
      fs.copyFileSync(output.destination, backupPath, fs.constants.COPYFILE_EXCL)
      backups.push({ destination: output.destination, backupPath })
    }

    for (const output of staged) {
      fs.renameSync(output.temporaryPath, output.destination)
      promoted.add(output.destination)
    }
  } catch (error) {
    for (const output of [...outputs].reverse()) {
      const backup = backups.find(candidate => candidate.destination === output.destination)
      if (backup && fs.existsSync(backup.backupPath)) {
        fs.renameSync(backup.backupPath, output.destination)
      } else if (promoted.has(output.destination)) {
        fs.rmSync(output.destination, { force: true })
      }
    }
    throw error
  } finally {
    for (const output of staged) fs.rmSync(output.temporaryPath, { force: true })
    for (const backup of backups) fs.rmSync(backup.backupPath, { force: true })
  }
}

